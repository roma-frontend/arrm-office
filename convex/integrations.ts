/** Default imID OAuth endpoints — used when no path override is saved. */
const IMID_AUTHORIZE_DEFAULT = 'https://api.imid.am/v1/oauth/authorize';
const IMID_USERINFO_DEFAULT = 'https://api.imid.am/v1/oauth/userinfo';
const IMID_SIGNING_DEFAULT = 'https://api.imid.am/v1/sign';

/** Result of an imID employee verification request. */
type ImidVerifyResult =
  | { verified: boolean; method: 'sub' }
  | { verified: false; method: 'phone'; requestId?: string; message: string };

/** Result of an imID login callback; returned via the HTTP handler redirect. */
type ImidLoginResult =
  | { status: 'error'; message: string }
  | {
      status: 'ok';
      sessionToken: string;
      sessionExpiry: number;
      userId: Id<'users'>;
      isNewUser: boolean;
      needsApproval: boolean;
    };

/**
 * Generate the authorize URL for the imID OAuth login flow.
 *
 * The frontend calls this query, then redirects the browser to the returned URL.
 * After authentication, imID redirects to the callback endpoint with an
 * authorization code that `imidLoginCallback` exchanges for a session.
 */
export const imidGetAuthorizationUrl = mutation({
  args: { organizationId: v.id('organizations') },
  handler: async (ctx, { organizationId }) => {
    // Public mutation — called from the login page before the user is authenticated.
    // Must be a mutation because it writes the OAuth state to the config.
    // CSRF protection is provided by the OAuth state parameter.
    const config = await ctx.db
      .query('integrationConfigs')
      .withIndex('by_org_provider', (q) =>
        q.eq('organizationId', organizationId).eq('provider', 'imid'),
      )
      .first();

    if (!config || !config.config.isEnabled || !config.config.enableLogin) {
      throw new Error('imID login is not enabled for this organization');
    }
    if (!config.config.clientId || !config.config.redirectUri) {
      throw new Error('imID: Client ID and Redirect URI must be configured');
    }

    const authorizeUrl = assertSafeUrl(
      config.config.authorizePath || IMID_AUTHORIZE_DEFAULT,
      'imID authorize URL',
    );

    // Generate a secure random state parameter to prevent CSRF.
    const stateBytes = new Uint8Array(32);
    crypto.getRandomValues(stateBytes);
    const state = Array.from(stateBytes)
      .map((b) => b.toString(16).padStart(2, '0'))
      .join('');

    // Persist the state so the callback can validate it.
    await ctx.db.patch(config._id, {
      config: { ...config.config, oauthState: state },
    });

    const params = new URLSearchParams({
      client_id: config.config.clientId,
      redirect_uri: config.config.redirectUri,
      response_type: 'code',
      scope: 'openid profile email',
      state,
    });

    return { url: `${authorizeUrl}?${params.toString()}`, state };
  },
});

/**
 * Exchange an OAuth authorization code for an access token from imID.
 * Used by `imidLoginCallback` to complete the OAuth flow.
 */
export const imidExchangeCode = internalAction({
  args: {
    organizationId: v.id('organizations'),
    code: v.string(),
    redirectUri: v.string(),
  },
  handler: async (ctx, { organizationId, code, redirectUri }) => {
    const config = await ctx.runQuery(internal.integrations.getIntegrationConfigInternal, {
      organizationId,
      provider: 'imid',
    });
    if (!config) throw new Error('imID config not found');

    const tokenUrl = assertSafeUrl(
      config.config.tokenPath || 'https://api.imid.am/v1/oauth/token',
      'imID token URL',
    );

    const { clientId, clientSecret } = config.config;
    if (!clientId || !clientSecret) {
      throw new Error('imID: Client ID and Client Secret must be configured');
    }

    const payload = await fetchTokenEndpoint(
      tokenUrl,
      {
        client_id: clientId,
        client_secret: clientSecret,
        grant_type: 'authorization_code',
        code,
        redirect_uri: redirectUri,
      },
      'imID token exchange',
      config.config,
    );

    const accessToken =
      asString(payload.access_token) ?? asString(payload.accessToken) ?? asString(payload.token);
    if (!accessToken) {
      throw new Error('imID: token exchange succeeded but no access_token was returned');
    }

    const idToken = asString(payload.id_token);

    return { accessToken, idToken, raw: payload };
  },
});

/**
 * Fetch user info from the imID userinfo endpoint using the access token.
 * Returns the user's email, name, and any other available claims.
 */
export const imidGetUserInfo = internalAction({
  args: {
    organizationId: v.id('organizations'),
    accessToken: v.string(),
  },
  handler: async (ctx, { organizationId, accessToken }) => {
    const config = await ctx.runQuery(internal.integrations.getIntegrationConfigInternal, {
      organizationId,
      provider: 'imid',
    });
    if (!config) throw new Error('imID config not found');

    const userInfoUrl = assertSafeUrl(
      config.config.userInfoPath || IMID_USERINFO_DEFAULT,
      'imID userinfo URL',
    );

    const payload = (await fetchJson(
      userInfoUrl,
      {
        method: 'GET',
        headers: {
          Authorization: `Bearer ${accessToken}`,
          Accept: 'application/json',
        },
      },
      'imID userinfo',
      config.config,
    )) as Record<string, unknown>;

    const email =
      asString(payload.email) ??
      asString(payload.preferred_username) ??
      asString(payload.sub) ??
      '';
    const nameRaw = asString(payload.name);
    const given = asString(payload.given_name);
    const family = asString(payload.family_name);
    const name = nameRaw || [given, family].filter(Boolean).join(' ') || 'User';
    const sub = asString(payload.sub) ?? email;
    const phone = asString(payload.phone_number) ?? asString(payload.phone);

    if (!email) {
      throw new Error('imID: userinfo did not return an email');
    }

    return {
      sub,
      email: email.toLowerCase(),
      name,
      phone,
      raw: payload,
    };
  },
});

/**
 * Clear the one-time OAuth state from the imID integration config.
 * Extracted into a mutation because `imidLoginCallback` is an internal action
 * and has no direct `ctx.db`.
 */
export const clearImidOauthState = internalMutation({
  args: { configId: v.id('integrationConfigs') },
  handler: async (ctx, { configId }) => {
    const doc = await ctx.db.get(configId);
    if (!doc) return;
    const cleaned: Record<string, unknown> = { ...doc.config };
    delete cleaned.oauthState;
    await ctx.db.patch(configId, { config: cleaned as Doc<'integrationConfigs'>['config'] });
  },
});

/**
 * Full OAuth login callback — exchange code, fetch user, create/login.
 * Called from the HTTP handler after imID redirects the user back.
 *
 * Returns a signed session token the HTTP handler bakes into the redirect
 * cookie, so the user lands in the app already authenticated.
 */
export const imidLoginCallback = internalAction({
  args: {
    organizationId: v.id('organizations'),
    code: v.string(),
    state: v.string(),
  },
  // Annotated explicitly: the handler calls ctx.runAction through
  // internal.integrations which creates a circular reference — without the
  // annotation TS cannot break the inference cycle.
  handler: async (ctx, { organizationId, code, state }): Promise<ImidLoginResult> => {
    const config = await ctx.runQuery(internal.integrations.getIntegrationConfigInternal, {
      organizationId,
      provider: 'imid',
    });
    if (!config) {
      return { status: 'error', message: 'imID configuration not found' } as const;
    }

    // Validate state (CSRF protection).
    if (config.config.oauthState && config.config.oauthState !== state) {
      return {
        status: 'error',
        message: 'Invalid state parameter — possible CSRF attack',
      } as const;
    }

    // Clear the state regardless of outcome (one-time use).
    await ctx.runMutation(internal.integrations.clearImidOauthState, { configId: config._id });

    const redirectUri = config.config.redirectUri || '';
    if (!redirectUri) {
      return { status: 'error', message: 'Redirect URI not configured' } as const;
    }

    // Exchange the authorization code for an access token.
    let tokenResult: { accessToken: string; idToken?: string | null };
    try {
      tokenResult = await ctx.runAction(internal.integrations.imidExchangeCode, {
        organizationId,
        code,
        redirectUri,
      });
    } catch (error: any) {
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      return {
        status: 'error',
        message: error?.message ? String(error.message) : 'Token exchange failed',
      } as const;
    }

    // Fetch user info from imID.
    let userInfo: { sub: string; email: string; name: string; phone?: string };
    try {
      userInfo = await ctx.runAction(internal.integrations.imidGetUserInfo, {
        organizationId,
        accessToken: tokenResult.accessToken,
      });
    } catch (error: any) {
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      return {
        status: 'error',
        message: error?.message ? String(error.message) : 'Failed to fetch user info',
      } as const;
    }

    // Create or log in the user via the auth module.
    try {
      const sessionToken = crypto.randomUUID();
      const sessionExpiry = Date.now() + 7 * 24 * 60 * 60 * 1000; // 7 days

      const result = await ctx.runMutation(internal.integrations.imidUpsertUser, {
        organizationId,
        email: userInfo.email,
        name: userInfo.name,
        phone: userInfo.phone,
        imidSub: userInfo.sub,
        sessionToken,
        sessionExpiry,
      });

      return {
        status: 'ok',
        sessionToken,
        sessionExpiry,
        userId: result.userId,
        isNewUser: result.isNewUser,
        needsApproval: result.needsApproval,
      } as const;
    } catch (error: any) {
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      return {
        status: 'error',
        message: error?.message ? String(error.message) : 'Failed to create session',
      } as const;
    }
  },
});

/**
 * Upsert a user logging in via imID OAuth.
 *
 * If the user's email exists in this org → log them in.
 * If not → create a new user (pending approval unless first in org).
 */
export const imidUpsertUser = internalMutation({
  args: {
    organizationId: v.id('organizations'),
    email: v.string(),
    name: v.string(),
    phone: v.optional(v.string()),
    imidSub: v.string(),
    sessionToken: v.string(),
    sessionExpiry: v.number(),
  },
  handler: async (ctx, args) => {
    const { organizationId, email, name, phone, imidSub, sessionToken, sessionExpiry } = args;
    const normalizedEmail = email.toLowerCase().trim();

    // Look up the user by email within this org.
    const existing = await ctx.db
      .query('users')
      .withIndex('by_org_email', (q) =>
        q.eq('organizationId', organizationId).eq('email', normalizedEmail),
      )
      .first();

    if (existing) {
      if (!existing.isActive) {
        throw new Error('Your account has been deactivated. Contact your administrator.');
      }
      if (!existing.isApproved) {
        throw new Error('Your account is pending approval.');
      }

      // Update session and imID subject id.
      await ctx.db.patch(existing._id, {
        sessionToken,
        sessionExpiry,
        lastLoginAt: Date.now(),
        imidSub,
      });

      return { userId: existing._id, isNewUser: false, needsApproval: false };
    }

    // New user — check org limits and create.
    const org = await ctx.db.get(organizationId);
    if (!org || !org.isActive) throw new Error('Organization is inactive');

    const activeUsers = await ctx.db
      .query('users')
      .withIndex('by_org_active', (q) =>
        q.eq('organizationId', organizationId).eq('isActive', true),
      )
      .take(DEFAULT_LIST_CAP);

    if (activeUsers.length >= org.employeeLimit) {
      throw new Error('Organization has reached its employee limit');
    }

    const isFirstMember = activeUsers.length === 0;
    const role = isFirstMember ? 'admin' : 'employee';
    const isApproved = isFirstMember;

    const userId = await ctx.db.insert('users', {
      organizationId,
      name: name || normalizedEmail.split('@')[0] || 'User',
      email: normalizedEmail,
      passwordHash: '', // OAuth-only user
      phone,
      role,
      employeeType: 'staff',
      isActive: true,
      isApproved,
      approvedAt: isApproved ? Date.now() : undefined,
      imidSub,
      sessionToken: isApproved ? sessionToken : undefined,
      sessionExpiry: isApproved ? sessionExpiry : undefined,
      lastLoginAt: isApproved ? Date.now() : undefined,
      travelAllowance: 20000,
      paidLeaveBalance: 24,
      sickLeaveBalance: 10,
      familyLeaveBalance: 5,
      dayOffBalance: 6,
      maternityLeaveBalance: 0,
      studyLeaveBalance: 5,
      createdAt: Date.now(),
    });

    if (!isApproved) {
      // Notify admins.
      const admins = await ctx.db
        .query('users')
        .withIndex('by_org_role', (q) => q.eq('organizationId', organizationId).eq('role', 'admin'))
        .take(20);

      for (const admin of admins) {
        await ctx.db.insert('notifications', {
          organizationId,
          userId: admin._id,
          type: 'join_request',
          title: '🙋 New imID Sign-Up',
          message: `${name} (${normalizedEmail}) signed up with imID and wants to join ${org.name || 'organization'}.`,
          isRead: false,
          relatedId: userId,
          route: '/organization',
          createdAt: Date.now(),
        });
      }
    }

    return { userId, isNewUser: true, needsApproval: !isApproved };
  },
});

