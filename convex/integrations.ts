/**
 * Process an inbound imID verify webhook callback.
 *
 * Called from the HTTP handler because `httpAction` has no direct `ctx.db`.
 * Validates the organization, parses the webhook body, and logs the
 * verification result.
 */
export const ingestImidVerifyCallback = internalAction({
  args: {
    organizationIdRaw: v.string(),
    body: v.string(),
  },
  handler: async (ctx, { organizationIdRaw, body }) => {
    const organizationId = await ctx.runQuery(internal.integrations.normalizeOrganizationId, {
      organizationIdRaw,
    });
    if (!organizationId) {
      return { status: 'invalid', message: 'Unknown organization' } as const;
    }

    let payload: Record<string, unknown>;
    try {
      payload = JSON.parse(body) as Record<string, unknown>;
    } catch {
      return { status: 'invalid', message: 'Body was not valid JSON' } as const;
    }

    const verified = payload.verified === true || payload.status === 'verified';

    if (verified) {
      await ctx.runMutation(internal.integrations.logSync, {
        organizationId,
        provider: 'imid',
        action: 'verification_completed',
        status: 'success',
        message: 'Phone verification completed successfully',
      });
    }

    return { status: 'ok', message: 'Verified' } as const;
  },
});

