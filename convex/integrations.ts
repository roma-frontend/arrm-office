/** Header carrying the hex HMAC-SHA256 of `<timestamp>.<body>`. */
export const WEBHOOK_SIGNATURE_HEADER = 'x-luckycarrot-signature';
/** Header carrying the unix-seconds timestamp that is signed alongside the body. */
export const WEBHOOK_TIMESTAMP_HEADER = 'x-luckycarrot-timestamp';

/** Deliveries older than this are rejected, so a captured request cannot be replayed. */
const WEBHOOK_MAX_SKEW_MS = 5 * 60 * 1000;

/** Refuse oversized bodies before spending CPU on HMAC or JSON parsing. */
export const WEBHOOK_MAX_BODY_BYTES = 1_000_000;

/** Outcome of an inbound delivery; the HTTP layer maps this to a status code. */
type WebhookOutcome =
  | { status: 'unauthorized' }
  | { status: 'disabled' }
  | { status: 'invalid'; message: string }
  | { status: 'ok'; message: string; created: number; updated: number; skipped: number };

/**
 * Compare two hex digests without leaking where they diverge. A `===` here would
 * finish early on the first differing character, which is a timing oracle an
 * attacker can walk one nibble at a time to forge a signature.
 */
function timingSafeEqualHex(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) {
    diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  }
  return diff === 0;
}

function toHex(buffer: ArrayBuffer): string {
  return Array.from(new Uint8Array(buffer))
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('');
}

/** HMAC-SHA256 over `<timestamp>.<body>`, hex-encoded. */
async function signWebhookPayload(
  secret: string,
  timestamp: string,
  body: string,
): Promise<string> {
  const key = await crypto.subtle.importKey(
    'raw',
    new TextEncoder().encode(secret),
    { name: 'HMAC', hash: 'SHA-256' },
    false,
    ['sign'],
  );
  const mac = await crypto.subtle.sign(
    'HMAC',
    key,
    new TextEncoder().encode(`${timestamp}.${body}`),
  );
  return toHex(mac);
}

