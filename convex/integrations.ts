/**
 * Authenticate and apply one inbound Lucky Carrot delivery.
 *
 * Kept out of the HTTP handler so the signing secret never enters the routing
 * layer, and so the whole path is unit-testable without a live request.
 *
 * Unlike a scheduled sync this never deactivates anyone: a webhook payload is
 * usually a single event or a partial page, and treating "absent from this push"
 * as "no longer employed" would lock out the whole organization.
 */
export const ingestLuckyCarrotWebhook = internalAction({
  args: {
    organizationIdRaw: v.string(),
    body: v.string(),
    signature: v.string(),
    timestamp: v.string(),
  },
  handler: async (ctx, args): Promise<WebhookOutcome> => {
    const { organizationIdRaw, body, signature, timestamp } = args;

    if (!signature || !timestamp) return { status: 'unauthorized' };

    const auth: {
      organizationId: Id<'organizations'>;
      secret: string;
      isEnabled: boolean;
      employeesListKey?: string;
      fieldMap?: string;
    } | null = await ctx.runQuery(internal.integrations.getWebhookAuth, { organizationIdRaw });
    // An unknown org, an unconfigured provider and a bad signature are all
    // reported identically — otherwise this endpoint enumerates organizations.
    if (!auth) return { status: 'unauthorized' };

    const sentAt = Number(timestamp);
    if (!Number.isFinite(sentAt)) return { status: 'unauthorized' };
    // Seconds and milliseconds are both accepted; senders differ.
    const sentAtMs = sentAt > 1e11 ? sentAt : sentAt * 1000;
    if (Math.abs(Date.now() - sentAtMs) > WEBHOOK_MAX_SKEW_MS) {
      return { status: 'unauthorized' };
    }

    const expected = await signWebhookPayload(auth.secret, timestamp, body);
    if (!timingSafeEqualHex(signature.trim().toLowerCase(), expected)) {
      return { status: 'unauthorized' };
    }

    // Past this line the sender is proven authentic, so it is safe to give it
    // specific feedback — and to write to the sync log without letting an
    // anonymous caller flood the table.
    if (!auth.isEnabled) return { status: 'disabled' };

    let payload: unknown;
    try {
      payload = JSON.parse(body);
    } catch {
      return { status: 'invalid', message: 'Body was not valid JSON' };
    }

    let records: unknown[];
    try {
      records = extractWebhookRecords(payload, auth.employeesListKey);
    } catch (error: any) {
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      return {
        status: 'invalid',
        message: error?.message ? String(error.message) : 'Unrecognized payload shape',
      };
    }

    if (records.length > MAX_IMPORT_RECORDS) {
      return {
        status: 'invalid',
        message: `Delivery contained ${records.length} records, above the ${MAX_IMPORT_RECORDS} per-request limit`,
      };
    }

    let normalized;
    try {
      normalized = normalizeEmployees(records, auth.fieldMap);
    } catch (error: any) {
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      return {
        status: 'invalid',
        message: error?.message ? String(error.message) : 'Could not read the payload',
      };
    }

    const { employees, dropped } = normalized;
    if (employees.length === 0) {
      return {
        status: 'invalid',
        message: `Received ${records.length} record(s) but none had a usable email — check the field mapping`,
      };
    }

    let created = 0;
    let updated = 0;
    let skipped = dropped;
    const notes: string[] = [];

    for (let i = 0; i < employees.length; i += UPSERT_BATCH_SIZE) {
      const res = await ctx.runMutation(internal.integrations.upsertEmployeeBatch, {
        organizationId: auth.organizationId,
        provider: 'lucky_carrot' as const,
        employees: employees.slice(i, i + UPSERT_BATCH_SIZE),
      });
      created += res.created;
      updated += res.updated;
      skipped += res.skipped;
      notes.push(...res.notes);
    }

    const message = `Lucky Carrot webhook: ${created} created, ${updated} updated, ${skipped} skipped`;

    await ctx.runMutation(internal.integrations.logSync, {
      organizationId: auth.organizationId,
      provider: 'lucky_carrot' as const,
      action: 'webhook',
      status: 'success',
      message,
      created,
      updated,
      deactivated: 0,
      skipped,
      details: notes.length ? JSON.stringify(notes.slice(0, 50)) : undefined,
    });

    await ctx.runMutation(internal.integrations.markWebhookReceived, {
      organizationId: auth.organizationId,
    });

    return { status: 'ok', message, created, updated, skipped };
  },
});

/**
 * Mint a new webhook signing secret and return it once.
 *
 * Rotating invalidates the previous secret immediately, so the value must be
 * copied into Lucky Carrot before the next delivery. It is deliberately absent
 * from every read path (see SERVER_ONLY_FIELDS) — this mutation's return value
 * is the only time it is ever transmitted.
 */
export const rotateWebhookSecret = mutation({
  args: { organizationId: v.id('organizations') },
  handler: async (ctx, { organizationId }) => {
    const caller = await getAuthCaller(ctx);
    if (!caller) throw new Error('Not authenticated');
    if (!canAdminOrg(caller, organizationId)) {
      throw new Error('Only admins of this organization can manage webhooks');
    }

    const existing = await ctx.db
      .query('integrationConfigs')
      .withIndex('by_org_provider', (q) =>
        q.eq('organizationId', organizationId).eq('provider', 'lucky_carrot'),
      )
      .first();
    if (!existing) {
      throw new Error('Save the Lucky Carrot configuration before generating a webhook secret');
    }

    // 256 bits of entropy, hex-encoded — the same shape the HMAC key expects.
    const bytes = new Uint8Array(32);
    crypto.getRandomValues(bytes);
    const secret = Array.from(bytes)
      .map((b) => b.toString(16).padStart(2, '0'))
      .join('');

    const now = Date.now();
    await ctx.db.patch(existing._id, {
      config: { ...existing.config, webhookSecret: secret },
      updatedAt: now,
    });

    await ctx.db.insert('auditLogs', {
      organizationId,
      userId: caller._id,
      action: 'integration_lucky_carrot_webhook_secret_rotated',
      target: 'lucky_carrot',
      details: JSON.stringify({ rotated: true }),
      createdAt: now,
    });

    return { secret };
  },
});

