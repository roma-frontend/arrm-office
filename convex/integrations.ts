/**
 * Third-party error bodies can echo back the credentials we sent, and they land
 * in sync logs shown in the UI. Truncate and strip anything secret-looking.
 */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
function safeErrorBody(body: string, config: any): string {
  let out = body.slice(0, 300);
  for (const field of SECRET_FIELDS) {
    const secret = config?.[field];
    if (typeof secret === 'string' && secret.length >= 6) {
      out = out.split(secret).join(SECRET_MASK);
    }
  }
  if (typeof config?.imidAccessToken === 'string' && config.imidAccessToken.length >= 6) {
    out = out.split(config.imidAccessToken).join(SECRET_MASK);
  }
  return out;
}

/**
 * Base64 of a UTF-8 string, for HTTP Basic credentials.
 *
 * `btoa` alone throws on any code point above U+00FF, so an Armenian username
 * or password — entirely normal for an Armenian ERP — would fail the sync
 * before a request was ever made. RFC 7617 §2.1 lets the client pick the
 * charset and names UTF-8 as the one to prefer, so encode to UTF-8 bytes first
 * and hand `btoa` the latin1 view it actually accepts.
 */
function basicAuthHeader(username: string, password: string): string {
  const bytes = new TextEncoder().encode(`${username}:${password}`);
  let latin1 = '';
  for (const byte of bytes) latin1 += String.fromCharCode(byte);
  return `Basic ${btoa(latin1)}`;
}

/** Join a base URL and path without doubling or dropping the separator. */
function joinUrl(base: string, path: string): string {
  const b = base.replace(/\/+$/, '');
  const p = path.startsWith('/') ? path : `/${path}`;
  return `${b}${p}`;
}

/** Reject non-HTTPS and obviously internal targets — configs are admin-supplied. */
function assertSafeUrl(raw: string, label: string): string {
  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    throw new Error(`${label}: "${raw.slice(0, 60)}" is not a valid URL`);
  }
  if (url.protocol !== 'https:') {
    throw new Error(`${label}: only https:// endpoints are allowed`);
  }
  const host = url.hostname.toLowerCase();
  const isPrivate =
    host === 'localhost' ||
    host === '::1' ||
    host.endsWith('.localhost') ||
    host.endsWith('.internal') ||
    /^127\./.test(host) ||
    /^10\./.test(host) ||
    /^192\.168\./.test(host) ||
    /^169\.254\./.test(host) ||
    /^172\.(1[6-9]|2\d|3[01])\./.test(host);
  if (isPrivate) {
    throw new Error(`${label}: private and loopback hosts are not allowed`);
  }
  return url.toString();
}

/** A provider call that fails or stalls must not hang the whole sync. */
async function fetchJson(
  url: string,
  init: RequestInit,
  label: string,
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  config: any,
): Promise<unknown> {
  let response: Response;
  try {
    response = await fetch(url, {
      ...init,
      signal: AbortSignal.timeout(20_000),
    });
  } catch (e: any) {
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const reason = e?.name === 'TimeoutError' ? 'request timed out' : 'network error';
    throw new Error(`${label}: ${reason}`);
  }

  if (!response.ok) {
    const body = await response.text().catch(() => '');
    throw new Error(`${label} API error (${response.status}): ${safeErrorBody(body, config)}`);
  }

  const text = await response.text();
  if (!text.trim()) {
    throw new Error(`${label}: empty response body`);
  }
  try {
    return JSON.parse(text);
  } catch {
    throw new Error(`${label}: response was not JSON — ${safeErrorBody(text, config)}`);
  }
}

/**
 * Call an OAuth 2.0 token endpoint.
 *
 * RFC 6749 §4.1.3 mandates `application/x-www-form-urlencoded` for token
 * requests, so that is what we send first. Some providers only accept JSON,
 * so a 400/415 response — the two statuses a server uses to reject a body it
 * cannot parse — triggers one retry with a JSON body. Any other failure is
 * a genuine error (bad credentials, wrong URL) and propagates immediately.
 */
async function fetchTokenEndpoint(
  url: string,
  params: Record<string, string>,
  label: string,
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  config: any,
): Promise<Record<string, unknown>> {
  try {
    return (await fetchJson(
      url,
      {
        method: 'POST',
        headers: {
          'Content-Type': 'application/x-www-form-urlencoded',
          Accept: 'application/json',
        },
        body: new URLSearchParams(params).toString(),
      },
      label,
      config,
    )) as Record<string, unknown>;
  } catch (e: any) {
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const message = String(e?.message ?? '');
    // Only retry when the server rejected the *encoding*, not the credentials.
    if (!/\((400|415)\)/.test(message)) throw e;

    return (await fetchJson(
      url,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
        body: JSON.stringify(params),
      },
      label,
      config,
    )) as Record<string, unknown>;
  }
}

