/**
 * A webhook may carry a whole directory or a single employee event. `extractList`
 * covers the collection shapes; fall back to the common single-record envelopes
 * so a "employee.updated" push does not need a separate code path.
 */
function extractWebhookRecords(payload: unknown, listKey?: string): unknown[] {
  try {
    return extractList(payload, listKey);
  } catch (listError) {
    if (payload && typeof payload === 'object') {
      const envelope = payload as Record<string, unknown>;
      for (const key of ['employee', 'user', 'data', 'record', 'object']) {
        const candidate = envelope[key];
        if (candidate && typeof candidate === 'object' && !Array.isArray(candidate)) {
          return [candidate];
        }
      }
      // A bare employee object posted at the top level.
      if (!Array.isArray(payload)) return [payload];
    }
    throw listError;
  }
}

/**
 * Credentials needed to authenticate an inbound delivery. Takes the org id as a
 * raw string because it arrives from the URL — `normalizeId` both validates it
 * and rejects ids belonging to another table.
 */
export const getWebhookAuth = internalQuery({
  args: { organizationIdRaw: v.string() },
  handler: async (ctx, { organizationIdRaw }) => {
    const organizationId = ctx.db.normalizeId('organizations', organizationIdRaw);
    if (!organizationId) return null;

    const doc = await ctx.db
      .query('integrationConfigs')
      .withIndex('by_org_provider', (q) =>
        q.eq('organizationId', organizationId).eq('provider', 'lucky_carrot'),
      )
      .first();
    if (!doc?.config.webhookSecret) return null;

    return {
      organizationId,
      secret: doc.config.webhookSecret,
      // Enablement is reported rather than enforced here: the caller checks the
      // signature first, so a legitimate sender gets a clear "disabled" answer
      // while an unauthenticated one learns nothing.
      isEnabled: doc.config.isEnabled === true && doc.config.webhookEnabled === true,
      employeesListKey: doc.config.employeesListKey,
      fieldMap: doc.config.fieldMap,
    };
  },
});

