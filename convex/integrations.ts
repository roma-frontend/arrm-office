/**
 * Verify an employee's identity through imID.
 *
 * Uses the cached access token and expects the user's imID subject ID (sub)
 * to have been stored on the user record during OAuth login. If the user has
 * never logged in via imID, a phone-based verification can be used instead.
 */
export const imidVerifyEmployee = action({
  args: {
    organizationId: v.id('organizations'),
    userId: v.id('users'),
    /** Used when the user has no imID sub — send verification to their phone. */
    phone: v.optional(v.string()),
  },
  // Annotated explicitly: the handler reaches into `internal.integrations` for
  // authorization and verification, creating a circular reference that TS
  // cannot break without an explicit return type annotation.
  handler: async (ctx, args): Promise<ImidVerifyResult> => {
    const caller = await ctx.runQuery(internal.integrations.assertCanSync, {
      organizationId: args.organizationId,
    });
    if (!caller) throw new Error('Not authorized');

    const config = await ctx.runQuery(internal.integrations.getIntegrationConfigInternal, {
      organizationId: args.organizationId,
      provider: 'imid',
    });
    if (!config || !config.config.isEnabled || !config.config.enableVerification) {
      throw new Error('imID Verification is not enabled for this organization');
    }

    const accessToken = config.config.imidAccessToken;
    if (!accessToken) {
      throw new Error('imID: no cached access token — run Sync first');
    }
    if (config.config.imidTokenExpiresAt && config.config.imidTokenExpiresAt < Date.now()) {
      throw new Error('imID: cached token has expired — run Sync to refresh');
    }

    const user = await ctx.runQuery(internal.integrations.getUserForVerification, {
      userId: args.userId,
    });
    if (!user) throw new Error('User not found');

    // Try subject-based verification first (user logged in via imID before).
    if (user.imidSub) {
      const verifyUrl = assertSafeUrl(
        config.config.userInfoPath || IMID_USERINFO_DEFAULT,
        'imID verify URL',
      );

      const payload = (await fetchJson(
        verifyUrl,
        {
          method: 'GET',
          headers: {
            Authorization: `Bearer ${accessToken}`,
            Accept: 'application/json',
          },
        },
        'imID verification',
        config.config,
      )) as Record<string, unknown>;

      const verified =
        asString(payload.sub) === user.imidSub ||
        asString(payload.email)?.toLowerCase() === user.email.toLowerCase();

      await ctx.runMutation(internal.integrations.logSync, {
        organizationId: args.organizationId,
        provider: 'imid',
        action: 'verification',
        status: verified ? 'success' : 'error',
        message: verified
          ? `Verified ${user.name} (${user.email}) via imID`
          : `Verification failed for ${user.email}`,
      });

      return { verified, method: 'sub' };
    }

    // Fallback: phone-based verification request.
    if (args.phone) {
      const verifyUrl = assertSafeUrl(
        config.config.signingPath || IMID_SIGNING_DEFAULT,
        'imID verify URL',
      );

      const payload = (await fetchJson(
        `${verifyUrl}/verify`,
        {
          method: 'POST',
          headers: {
            Authorization: `Bearer ${accessToken}`,
            'Content-Type': 'application/json',
            Accept: 'application/json',
          },
          body: JSON.stringify({
            phone: args.phone,
            purpose: 'employee_verification',
            callback_url: `${process.env.CONVEX_SITE_URL || ''}/webhooks/imid/verify`,
          }),
        },
        'imID phone verification',
        config.config,
      )) as Record<string, unknown>;

      const requestId = asString(payload.request_id) ?? asString(payload.id);

      return {
        verified: false,
        method: 'phone',
        requestId,
        message: `Verification request sent to ${args.phone}`,
      };
    }

    throw new Error('imID: cannot verify — user has no imID subject and no phone was provided');
  },
});

/**
 * Resolve an organization id from an OAuth state parameter.
 *
 * Scans all imID integration configs for a matching `oauthState`.
 * This is an action instead of a query because httpActions cannot call queries
 * with arbitrary args — but they can call actions. The action delegates to an
 * internal query internally.
 */
export const imidResolveOrgByState = internalAction({
  args: { state: v.string() },
  // Annotated explicitly: the handler queries internal.integrations which
  // creates a circular reference — without the annotation TS cannot break
  // the inference cycle.
  handler: async (ctx, { state }): Promise<{ organizationId: Id<'organizations'> } | null> => {
    // We need to scan configs, so use the internal list query.
    const configs = await ctx.runQuery(internal.integrations.listAllImidConfigs, {});
    for (const cfg of configs) {
      if (cfg.oauthState === state) {
        return { organizationId: cfg.organizationId };
      }
    }
    return null;
  },
});

